import { prisma } from '@/lib/prisma';
import { LedgerService } from './ledger.service';
import { FiscalPeriodService } from './fiscal-period.service';
import { LedgerReportService } from './ledger-report.service';
import { FiscalPeriodStatus, Prisma } from '@prisma/client';
import { AppError } from '@/lib/error';
import { ACCOUNTS } from './account-codes';
import { AuditLedgerService } from '@/services/inventory/audit-ledger.service';
import { assertProjectAccess } from '@/lib/project-access';
import { resolveOpmcScope } from '@/lib/opmc-scope';
export interface CreditDebitNotePayload {
    noteNumber?: string;
    type?: 'CREDIT_NOTE' | 'DEBIT_NOTE';
    invoiceId?: string;
    amount: number;
    reason: string;
    createdById?: string;
}
export class PeriodCloseService {
    /**
     * Execute formal Year-End Close: zero P&L accounts, roll Net Profit into Retained Earnings (EQU-RET-3010), and lock periods.
     */
    static async executeYearEndClose(year: number, closedById?: string) {
        if (!Number.isInteger(year) || year < 2000 || year >= new Date().getFullYear()) {
            throw AppError.badRequest('Only a completed fiscal year can be closed');
        }
        if (!closedById) throw AppError.unauthorized('Authenticated finance approver is required');
        return await prisma.$transaction(async (tx) => {
            const idempotencyKey = `YEAR_END_CLOSE:${year}`;
            const previousClose = await tx.journalEntry.findUnique({ where: { idempotencyKey } });
            if (previousClose) throw AppError.conflict(`Fiscal year ${year} is already closed`);
            const lockedPeriods = await tx.fiscalPeriod.count({ where: { year, status: FiscalPeriodStatus.LOCKED } });
            if (lockedPeriods === 12) throw AppError.conflict(`Fiscal year ${year} is already locked`);
            const pendingEntries = await tx.journalEntry.count({
                where: { date: { gte: new Date(year, 0, 1), lt: new Date(year + 1, 0, 1) }, status: { in: ['DRAFT', 'PENDING_APPROVAL'] } },
            });
            if (pendingEntries > 0) throw AppError.conflict(`${pendingEntries} journal entries are awaiting approval`);
            // 1. Fetch Trial Balance for the entire fiscal year
            const fromDate = new Date(year, 0, 1);
            const toDate = new Date(new Date(year + 1, 0, 1).getTime() - 1);
            const tb = await LedgerReportService.getAccountBalances(fromDate, toDate, tx);
            if (!tb.isBalanced) throw AppError.conflict('Trial balance is not balanced');
            let totalRevenue = 0;
            let totalExpense = 0;
            const zeroingLines: { accountCode: string; debit: number; credit: number; description: string }[] = [];
            for (const a of tb.accounts) {
                const typeStr = String(a.type);
                if (typeStr === 'REVENUE' && a.netBalance !== 0) {
                    totalRevenue += a.netBalance;
                    zeroingLines.push({
                        accountCode: a.code,
                        debit: Math.max(a.netBalance, 0),
                        credit: Math.max(-a.netBalance, 0),
                        description: `Year-End P&L Close for ${a.code}`
                    });
                } else if (typeStr === 'EXPENSE' && a.netBalance !== 0) {
                    totalExpense += a.netBalance;
                    zeroingLines.push({
                        accountCode: a.code,
                        debit: Math.max(-a.netBalance, 0),
                        credit: Math.max(a.netBalance, 0),
                        description: `Year-End P&L Close for ${a.code}`
                    });
                }
            }
            const netProfit = totalRevenue - totalExpense;
            // Post Net Profit/Loss to Retained Earnings (EQUITY-3000)
            if (netProfit > 0) {
                zeroingLines.push({
                    accountCode: ACCOUNTS.RETAINED_EARNINGS,
                    debit: 0,
                    credit: netProfit,
                    description: `Net Income Rollover to Retained Earnings FY ${year}`
                });
            } else if (netProfit < 0) {
                zeroingLines.push({
                    accountCode: ACCOUNTS.RETAINED_EARNINGS,
                    debit: Math.abs(netProfit),
                    credit: 0,
                    description: `Net Loss Rollover to Retained Earnings FY ${year}`
                });
            }
            let journalEntry = null;
            if (zeroingLines.length > 0) {
                journalEntry = await LedgerService.postTransaction(tx, {
                    idempotencyKey,
                    referenceType: 'YEAR_END_CLOSE',
                    isAutoGenerated: true,
                    description: `Formal Year-End Close and Retained Earnings Rollover FY ${year}`,
                    date: toDate,
                    createdById: closedById,
                    lines: zeroingLines
                });
            }
            // Lock all 12 fiscal periods for the year
            for (let month = 1; month <= 12; month++) {
                await FiscalPeriodService.setPeriodStatus(year, month, FiscalPeriodStatus.LOCKED, closedById, tx);
            }
            return {
                year,
                totalRevenue,
                totalExpense,
                netProfit,
                journalId: journalEntry?.id
            };
        });
    }
    /**
     * Create and post Credit or Debit Note against an invoice.
     */
    static async createCreditDebitNote(payload: CreditDebitNotePayload) {
        return await prisma.$transaction(async (tx) => {
            const { invoiceId, amount, reason, createdById } = payload;
            const noteType = payload.type || 'CREDIT_NOTE';
            if (!createdById) throw AppError.unauthorized('Authenticated finance approver is required');
            if (!Number.isFinite(amount) || amount <= 0 || !Number.isInteger(amount * 100)) {
                throw AppError.badRequest('Note amount must be greater than zero');
            }
            let invoice = null;
            if (invoiceId) {
                invoice = await tx.projectInvoice.findUnique({ where: { id: invoiceId } });
                if (!invoice) throw AppError.notFound(`Invoice #${invoiceId} not found`);
                await assertProjectAccess(invoice.projectId, createdById);
                if (noteType === 'CREDIT_NOTE' && amount > Number(invoice.balanceAmount) + Number(invoice.paidAmount)) {
                    throw AppError.badRequest('Credit note amount exceeds invoice amount');
                }
                if (noteType === 'CREDIT_NOTE' && Number(invoice.paidAmount) > 0) {
                    throw AppError.conflict('Credit notes cannot reduce an invoice after settlement has started');
                }
            }
            const docType = noteType === 'CREDIT_NOTE' ? 'CN' : 'DN';
            const noteNo = payload.noteNumber || await AuditLedgerService.getNextDocumentNumber(docType, tx);
            // 1. Create CreditDebitNote Record
            const note = await tx.creditDebitNote.create({
                data: {
                    noteNumber: noteNo,
                    type: noteType,
                    invoiceId: invoiceId || null,
                    amount,
                    reason,
                    status: 'POSTED',
                    createdById
                }
            });
            // 2. Adjust Invoice Balance
            if (invoice) {
                if (noteType === 'CREDIT_NOTE') {
                    const newBalance = Math.max(0, Number(invoice.balanceAmount) - amount);
                    await tx.projectInvoice.update({
                        where: { id: invoiceId },
                        data: { totalAmount: new Prisma.Decimal(invoice.totalAmount).minus(amount), balanceAmount: newBalance }
                    });
                } else {
                    const newBalance = invoice.balanceAmount.toNumber() + amount;
                    await tx.projectInvoice.update({
                        where: { id: invoiceId },
                        data: { totalAmount: new Prisma.Decimal(invoice.totalAmount).plus(amount), balanceAmount: newBalance }
                    });
                }
            }
            // 3. Post Double-Entry Journal:
            // Credit Note: DR Revenue / CR AR
            // Debit Note : DR AR / CR Revenue
            const lines = noteType === 'CREDIT_NOTE' ? [
                {
                    accountCode: ACCOUNTS.REVENUE,
                    debit: amount,
                    credit: 0,
                    description: `Credit Note #${noteNo} revenue adjustment`
                },
                {
                    accountCode: ACCOUNTS.AR_CLIENT,
                    debit: 0,
                    credit: amount,
                    description: `Credit Note #${noteNo} AR balance reduction`
                }
            ] : [
                {
                    accountCode: ACCOUNTS.AR_CLIENT,
                    debit: amount,
                    credit: 0,
                    description: `Debit Note #${noteNo} AR balance increase`
                },
                {
                    accountCode: ACCOUNTS.REVENUE,
                    debit: 0,
                    credit: amount,
                    description: `Debit Note #${noteNo} additional revenue charge`
                }
            ];
            const journal = await LedgerService.postTransaction(tx, {
                referenceId: note.id,
                referenceType: noteType,
                description: reason || `${noteType} #${noteNo} issued`,
                date: new Date(),
                createdById,
                isAutoGenerated: true,
                lines
            });
            const updatedNote = await tx.creditDebitNote.update({
                where: { id: note.id },
                data: { postedJournalId: journal.id }
            });
            return updatedNote;
        });
    }
    static async getCreditDebitNotes(userId?: string | null) {
        const scope = await resolveOpmcScope(userId);
        const where = scope === undefined
            ? undefined
            : { invoice: { project: { opmcId: { in: scope } } } };
        return await prisma.creditDebitNote.findMany({
            where,
            include: {
                invoice: true
            },
            orderBy: {
                createdAt: 'desc'
            }
        });
    }
}
