async function main() {
    console.log('=== Check R-KX August Completed SODs ===\n');
    console.log(`Total SODs to check: ${sodNumbers.length}\n`);

    // Check which SODs exist in database
    const existing = await primaryClient.serviceOrder.findMany({
        where: {
            soNum: { in: sodNumbers }
        },
        select: {
            soNum: true,
            status: true,
            sltsStatus: true,
            completedDate: true,
            opmcId: true
        }
    });

    console.log(`Found ${existing.length} SODs in database\n`);

    // Check which are missing
    const existingIds = new Set(existing.map(s => s.soNum));
    const missing = sodNumbers.filter(id => !existingIds.has(id));

    if (missing.length > 0) {
        console.log(`\nMissing SODs (not in database): ${missing.length}`);
        missing.slice(0, 20).forEach(id => console.log('  ' + id));
        if (missing.length > 20) console.log(`  ... and ${missing.length - 20} more`);
    }

    // Check status distribution
    const statusCounts: Record<string, number> = {};
    existing.forEach(s => {
        const key = `${s.status}/${s.sltsStatus}`;
        statusCounts[key] = (statusCounts[key] || 0) + 1;
    });

    console.log('\nStatus distribution:');
    Object.entries(statusCounts).forEach(([status, count]) => {
        console.log(`  ${status}: ${count}`);
    });

    // Check completed SODs
    const completed = existing.filter(s => 
        s.sltsStatus === 'COMPLETED' || 
        s.status === 'COMPLETED' ||
        s.sltsStatus === 'INSTALL_CLOSED' ||
        s.status === 'INSTALL_CLOSED'
    );
    console.log(`\nCompleted/Install-Closed: ${completed.length}`);

    // Check by month
    const byMonth: Record<string, number> = {};
    existing.forEach(s => {
        if (s.completedDate) {
            const month = new Date(s.completedDate).getMonth() + 1;
            byMonth[month.toString()] = (byMonth[month.toString()] || 0) + 1;
        }
    });
    console.log('\nBy completion month:');
    Object.entries(byMonth).forEach(([month, count]) => {
        console.log(`  Month ${month}: ${count}`);
    });
}

main()
    .catch(console.error)
    .finally(() => primaryClient.$disconnect());
